#!/usr/bin/env bash
# Regenerates every file in desktop/resources/ from the in-repo Grafana mark.
# Manual, designer-run step: not wired into CI or the root build. See ../README.md.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$OUT/../.." && pwd)"
MARK="$REPO_ROOT/public/img/grafana_icon.svg"
SRC="$OUT/src"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Theme values from packages/grafana-data/src/themes (palette.ts, createColors.ts).
GRAY05='#111217'           # palette.gray05 (dark background.canvas)
GRAY15='#22252b'           # palette.gray15 (dark background.secondary)
GRAY45='#6e7177'           # palette.gray45
GRAY90='#ececed'           # palette.gray90 (light secondary.main)
GRAY95='#f4f5f5'           # palette.gray95 (light background.secondary)
BRAND_START='#FF8833'      # dark gradients.brandHorizontal, 100% stop
BRAND_END='#F55F3E'        # dark gradients.brandHorizontal, 0% stop
FONT_FAMILY="'Inter', 'Helvetica', 'Arial', sans-serif" # typography.fontFamily
FONT_WEIGHT_MEDIUM=500     # typography.fontWeightMedium

need() { command -v "$1" >/dev/null 2>&1 || { echo "error: '$1' not found ($2)" >&2; exit 1; }; }
need rsvg-convert "apt install librsvg2-bin / brew install librsvg"
if command -v magick >/dev/null 2>&1; then IM=(magick); else need convert "apt install imagemagick / brew install imagemagick"; IM=(convert); fi
FONT_MATCH="$(fc-match -f '%{family}' Inter 2>/dev/null || true)"
if [[ "$FONT_MATCH" != *Inter* ]]; then
  echo "warning: Inter font not found; installer text will fall back (apt install fonts-inter)" >&2
fi
[[ -f "$MARK" ]] || { echo "error: mark not found at $MARK" >&2; exit 1; }

MARK_SHA="$(sha256sum "$MARK" 2>/dev/null || shasum -a 256 "$MARK")"
MARK_SHA="${MARK_SHA%% *}"
# Body of the mark verbatim (everything inside the root <svg> element), so the logo is never redrawn.
MARK_BODY="$(awk '
  /<svg/ { insvg = 1 }
  insvg && !open { if (/>[[:space:]]*$/) open = 1; next }
  open && /<\/svg>/ { exit }
  open { print }
' "$MARK")"
[[ -n "$MARK_BODY" ]] || { echo "error: could not extract mark body from $MARK" >&2; exit 1; }

MARK_W=351
MARK_H=365

# mark X Y HEIGHT -> the unmodified mark scaled uniformly to HEIGHT at (X, Y).
mark() {
  local w
  w="$(awk -v h="$3" -v mw="$MARK_W" -v mh="$MARK_H" 'BEGIN { printf "%.2f", h * mw / mh }')"
  printf '<svg x="%s" y="%s" width="%s" height="%s" viewBox="0 0 %s %s">\n%s\n</svg>\n' \
    "$1" "$2" "$w" "$3" "$MARK_W" "$MARK_H" "$MARK_BODY"
}

# tile X Y SIZE [MARK_RATIO] -> macOS-style rounded tile with the mark, using Apple's 824/1024 grid
# corner proportions. MARK_RATIO is mark height / tile size.
tile() {
  awk -v x="$1" -v y="$2" -v s="$3" 'BEGIN {
    printf "<rect x=\"%.2f\" y=\"%.2f\" width=\"%.2f\" height=\"%.2f\" rx=\"%.2f\" fill=\"url(#tile)\"/>\n", x, y, s, s, s * 185.4 / 824
  }'
  local mh mx my
  mh="$(awk -v s="$3" -v r="${4:-0.6796}" 'BEGIN { printf "%.2f", s * r }')"
  mx="$(awk -v x="$1" -v s="$3" -v mh="$mh" -v mw="$MARK_W" -v h="$MARK_H" 'BEGIN { printf "%.2f", x + (s - mh * mw / h) / 2 }')"
  my="$(awk -v y="$2" -v s="$3" -v mh="$mh" 'BEGIN { printf "%.2f", y + (s - mh) / 2 }')"
  mark "$mx" "$my" "$mh"
}

header() {
  printf '<?xml version="1.0" encoding="UTF-8"?>\n'
  printf '<!-- Generated by desktop/resources/scripts/build-icons.sh; edit the script, not this file. -->\n'
  printf '<!-- Mark: public/img/grafana_icon.svg sha256=%s -->\n' "$MARK_SHA"
}

defs() {
  cat <<EOF
<defs>
  <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="$GRAY15"/>
    <stop offset="1" stop-color="$GRAY05"/>
  </linearGradient>
  <linearGradient id="brand" x1="0" y1="0" x2="1" y2="0">
    <stop offset="0" stop-color="$BRAND_START"/>
    <stop offset="1" stop-color="$BRAND_END"/>
  </linearGradient>
  <filter id="shadow" x="-10%" y="-10%" width="120%" height="130%">
    <feDropShadow dx="0" dy="12" stdDeviation="14" flood-color="#000000" flood-opacity="0.3"/>
  </filter>
</defs>
EOF
}

mkdir -p "$SRC" "$OUT/icons"

# --- SVG sources -------------------------------------------------------------

{
  header
  printf '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
  defs
  printf '<g filter="url(#shadow)">\n'
  tile 100 100 824
  printf '</g>\n</svg>\n'
} >"$OUT/icon.svg"

# macOS 16/32 px slots: same tile near full-bleed with a larger mark; at 16 px the full grid leaves the mark ~9 px tall.
{
  header
  printf '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
  defs
  tile 24 24 976 0.76
  printf '</svg>\n'
} >"$SRC/icon-small.svg"

# Windows/Linux: bare mark, near full-bleed so 16/24/32 px stay legible.
{
  header
  printf '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
  mark 50.5 32 960
  printf '</svg>\n'
} >"$SRC/icon-flat.svg"

# Positions match electron-builder's dmg defaults: window 540x380, app at (130,220), Applications at (410,220), 80px icons.
{
  header
  cat <<EOF
<svg xmlns="http://www.w3.org/2000/svg" width="540" height="380" viewBox="0 0 540 380">
$(defs)
<rect width="540" height="380" fill="$GRAY45"/>
<text x="270" y="62" text-anchor="middle" font-family="$FONT_FAMILY" font-weight="$FONT_WEIGHT_MEDIUM" font-size="20" fill="$GRAY95">Install Grafana</text>
<text x="270" y="88" text-anchor="middle" font-family="$FONT_FAMILY" font-size="13" fill="$GRAY90">Drag Grafana onto the Applications folder</text>
<g fill="none" stroke="$GRAY95" stroke-width="4" stroke-linecap="round" stroke-linejoin="round">
  <path d="M206 220 H330" stroke-dasharray="2 12"/>
  <path d="M320 204 L338 220 L320 236"/>
</g>
<rect y="376" width="540" height="4" fill="url(#brand)"/>
</svg>
EOF
} >"$SRC/background.svg"

{
  header
  cat <<EOF
<svg xmlns="http://www.w3.org/2000/svg" width="164" height="314" viewBox="0 0 164 314">
$(defs)
<rect width="164" height="314" fill="$GRAY45"/>
$(tile 34 70 96)
<text x="82" y="200" text-anchor="middle" font-family="$FONT_FAMILY" font-weight="$FONT_WEIGHT_MEDIUM" font-size="20" fill="$GRAY95">Grafana</text>
<rect y="310" width="164" height="4" fill="url(#brand)"/>
</svg>
EOF
} >"$SRC/installerSidebar.svg"

{
  header
  cat <<EOF
<svg xmlns="http://www.w3.org/2000/svg" width="150" height="57" viewBox="0 0 150 57">
$(defs)
<rect width="150" height="57" fill="$GRAY45"/>
<text x="12" y="34" font-family="$FONT_FAMILY" font-weight="$FONT_WEIGHT_MEDIUM" font-size="16" fill="$GRAY95">Grafana</text>
$(tile 99 6 42)
<rect y="54" width="150" height="3" fill="url(#brand)"/>
</svg>
EOF
} >"$SRC/installerHeader.svg"

# --- Rasters -------------------------------------------------------------------

render() { rsvg-convert -w "$2" -h "$3" "$1" -o "$4"; }

# Linux: icons/<size>x<size>.png (electron-builder linux.icon default when icons/ exists).
for s in 16 32 48 64 128 256 512; do
  render "$SRC/icon-flat.svg" "$s" "$s" "$OUT/icons/${s}x${s}.png"
done

# Windows: icon.ico, each size rendered natively from vector rather than downscaled.
ico_inputs=()
for s in 16 24 32 48 64 128 256; do
  render "$SRC/icon-flat.svg" "$s" "$s" "$TMP/ico-$s.png"
  ico_inputs+=("$TMP/ico-$s.png")
done
"${IM[@]}" "${ico_inputs[@]}" "$OUT/icon.ico"

# macOS: icon.icns written directly (PNG payloads), so no iconutil is needed on Linux.
# OSType -> pixel size; ic11..ic14 and ic10 are the @2x variants of 16/32/128/256/512.
ICNS_TYPES=(icp4:16 ic11:32 icp5:32 ic12:64 ic07:128 ic13:256 ic08:256 ic14:512 ic09:512 ic10:1024)
be32() { printf "\\x$(printf %02x $((($1 >> 24) & 255)))\\x$(printf %02x $((($1 >> 16) & 255)))\\x$(printf %02x $((($1 >> 8) & 255)))\\x$(printf %02x $(($1 & 255)))"; }
filesize() { wc -c <"$1" | tr -d ' '; }
total=8
for entry in "${ICNS_TYPES[@]}"; do
  s="${entry#*:}"
  if [[ ! -f "$TMP/icns-$s.png" ]]; then
    if ((s <= 32)); then icns_src="$SRC/icon-small.svg"; else icns_src="$OUT/icon.svg"; fi
    render "$icns_src" "$s" "$s" "$TMP/icns-$s.png"
  fi
  total=$((total + 8 + $(filesize "$TMP/icns-$s.png")))
done
{
  printf 'icns'
  be32 "$total"
  for entry in "${ICNS_TYPES[@]}"; do
    type="${entry%%:*}"
    s="${entry#*:}"
    printf '%s' "$type"
    be32 $((8 + $(filesize "$TMP/icns-$s.png")))
    cat "$TMP/icns-$s.png"
  done
} >"$OUT/icon.icns"

# dmg background @1x/@2x; DPI tagged so macOS pairs them for Retina.
render "$SRC/background.svg" 540 380 "$TMP/bg1.png"
render "$SRC/background.svg" 1080 760 "$TMP/bg2.png"
"${IM[@]}" "$TMP/bg1.png" -alpha off -units PixelsPerInch -density 72 -define png:exclude-chunks=date,time,tEXt,zTXt "$OUT/background.png"
"${IM[@]}" "$TMP/bg2.png" -alpha off -units PixelsPerInch -density 144 -define png:exclude-chunks=date,time,tEXt,zTXt "$OUT/background@2x.png"

# NSIS: 24-bit uncompressed BMP3, no alpha channel.
for name in installerHeader:150:57 installerSidebar:164:314; do
  IFS=: read -r base w h <<<"$name"
  render "$SRC/$base.svg" "$w" "$h" "$TMP/$base.png"
  "${IM[@]}" "$TMP/$base.png" -background "$GRAY45" -alpha remove -alpha off -type TrueColor "BMP3:$OUT/$base.bmp"
done

echo "Generated assets in $OUT:"
(cd "$OUT" && ls -1 icon.svg icon.icns icon.ico background.png background@2x.png installerHeader.bmp installerSidebar.bmp icons/*.png src/*.svg)
